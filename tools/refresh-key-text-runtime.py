"""Refresh Credits-off proxies after the exact EXE table changes for 2.0.0.

The source build is external and task-owned. Historical proxy hashes stay in
medieval_state.h; this script only replaces currently packaged payloads after
checking their old manifests and the new build evidence.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RUNTIME = ROOT / "vendor" / "runtime"
NAMES = (
    "scroll-sprite-off", "scroll-sprite-off-fast",
    "scroll-sprite-off-icon-off", "scroll-sprite-off-fast-icon-off",
    "fast-only", "icon-only", "fast-icon",
    "scroll-sprite-off-zoom", "scroll-sprite-off-fast-zoom",
    "scroll-sprite-off-icon-off-zoom", "scroll-sprite-off-fast-icon-off-zoom",
    "zoom-only", "fast-only-zoom", "icon-only-zoom", "fast-icon-zoom",
)
SCAFFOLD = {
    "scroll-sprite-off": "scroll_sprite_off_sha256",
    "scroll-sprite-off-fast": "scroll_sprite_off_fast_sha256",
    "scroll-sprite-off-icon-off": "scroll_sprite_off_icon_off_sha256",
    "scroll-sprite-off-fast-icon-off": "scroll_sprite_off_fast_icon_off_sha256",
    "fast-only": "fast_only_sha256",
    "icon-only": "icon_only_sha256",
    "fast-icon": "fast_icon_sha256",
}


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest().upper()


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def header(rows: list[tuple[int, int, int, int, str, int]]) -> bytes:
    lines = [
        "/* Generated by tools/refresh-key-text-runtime.py from source-built Credits-off proxies. */",
        "#ifndef MTW_RUNTIME_PROXY_HASHES_H",
        "#define MTW_RUNTIME_PROXY_HASHES_H",
        "#include <stddef.h>",
        "#include <string.h>",
        "typedef struct MtwRuntimeProxyVariant {",
        "    unsigned char terrain, fast, icon, zoom;",
        "    const char *sha256;",
        "    size_t file_length;",
        "} MtwRuntimeProxyVariant;",
        "static const MtwRuntimeProxyVariant mtw_runtime_proxy_variants[] = {",
    ]
    for terrain, fast, icon, zoom, digest, length in rows:
        lines.append(f'    {{{terrain}u, {fast}u, {icon}u, {zoom}u, "{digest}", {length}u}},')
    lines += [
        "};",
        "static inline const MtwRuntimeProxyVariant *mtw_runtime_proxy_for_options(",
        "    unsigned int terrain, unsigned int fast, unsigned int icon, unsigned int zoom) {",
        "    size_t i;",
        "    for (i = 0u; i < sizeof(mtw_runtime_proxy_variants) / sizeof(mtw_runtime_proxy_variants[0]); ++i) {",
        "        const MtwRuntimeProxyVariant *v = &mtw_runtime_proxy_variants[i];",
        "        if (v->terrain == terrain && v->fast == fast && v->icon == icon && v->zoom == zoom)",
        "            return v;",
        "    }",
        "    return NULL;",
        "}",
        "static inline int mtw_runtime_proxy_known_hash(const char *sha256_hex) {",
        "    size_t i;",
        "    if (!sha256_hex) return 0;",
        "    for (i = 0u; i < sizeof(mtw_runtime_proxy_variants) / sizeof(mtw_runtime_proxy_variants[0]); ++i)",
        "        if (!strcmp(sha256_hex, mtw_runtime_proxy_variants[i].sha256)) return 1;",
        "    return 0;",
        "}",
        "#endif",
        "",
    ]
    return "\n".join(lines).encode("ascii")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    build = args.build.resolve()
    scaffold = read_json(build / "scaffold" / "BUILD_MANIFEST.json")
    zoom = read_json(build / "zoom-build-manifest.json")
    table_hash = sha256((ROOT / "include" / "mtw_exe_variants.h").read_bytes())
    if (scaffold.get("status") != "development_candidate" or
            scaffold.get("executable_variants_header_sha256") != table_hash or
            zoom.get("source_inputs", {}).get("include/mtw_exe_variants.h", {}).get("sha256") != table_hash or
            any(value != 0 for key, value in scaffold.items() if key.endswith("_tests_exit")) or
            scaffold.get("smoke_loader_exit") != 0):
        raise ValueError("Credits-off source build is incomplete or uses another executable table")
    for relative, record in zoom["source_inputs"].items():
        source = (ROOT / relative).resolve()
        if not source.is_relative_to(ROOT) or sha256(source.read_bytes()) != record["sha256"]:
            raise ValueError(f"Credits-off source changed: {relative}")
    zoom_records = {row["name"]: row for row in zoom["variants"]}
    if set(zoom_records) != {name for name in NAMES if "zoom" in name}:
        raise ValueError("Credits-off Zoom build is incomplete")
    pending: list[tuple[Path, bytes]] = []
    rows = []
    report = {"schema": "mtw-key-text-runtime-refresh-v1", "applied": args.apply,
              "identity_table_sha256": table_hash, "variants": []}
    for name in NAMES:
        filename = f"D3D9-{name}.dll"
        zoomed = "zoom" in name
        source = build / ("payloads" if zoomed else "scaffold/combined-r154") / filename
        target = RUNTIME / filename
        manifest_path = RUNTIME / f"payload-manifest-{name}.json"
        manifest = read_json(manifest_path)
        old = target.read_bytes()
        new = source.read_bytes()
        old_record = manifest["files"]["D3D9.dll"]
        if (old_record["sha256"], old_record["length"]) != (sha256(old), len(old)):
            raise ValueError(f"Current manifest does not pin {filename}")
        if manifest.get("credits_flash_fix_enabled"):
            raise ValueError(f"Credits-off payload enables Credits: {name}")
        if zoomed:
            evidence = zoom_records[name]
            if (evidence["sha256"], evidence["length"]) != (sha256(new), len(new)):
                raise ValueError(f"Zoom build does not pin {filename}")
        elif scaffold[SCAFFOLD[name]] != sha256(new):
            raise ValueError(f"Scaffold does not pin {filename}")
        if old == new:
            raise ValueError(f"Rebuilt proxy unexpectedly unchanged: {filename}")
        terrain = int(name.startswith("scroll-sprite-off"))
        fast = int("fast" in name)
        icon = int("icon-off" not in name) if terrain else int("icon" in name)
        zoom_flag = int(zoomed)
        rows.append((terrain, fast, icon, zoom_flag, sha256(new), len(new)))
        manifest["runtime_identity"] = f"R293-key-text-{name}"
        old_record.update(sha256=sha256(new), length=len(new))
        pending.extend(((target, new),
                        (manifest_path, (json.dumps(manifest, indent=2) + "\n").encode("utf-8"))))
        report["variants"].append({"name": name, "old_sha256": sha256(old),
                                   "new_sha256": sha256(new), "old_length": len(old),
                                   "new_length": len(new)})
    if len(set(rows)) != len(NAMES):
        raise ValueError("Credits-off source variants are ambiguous")
    base = RUNTIME / "D3D9.dll"
    base_manifest = RUNTIME / "payload-manifest.json"
    if (base.read_bytes() != (RUNTIME / "D3D9-scroll-sprite-off.dll").read_bytes() or
            base_manifest.read_bytes() != (RUNTIME / "payload-manifest-scroll-sprite-off.json").read_bytes()):
        raise ValueError("Default proxy alias differs from the selected base variant")
    default = next(data for path, data in pending if path.name == "D3D9-scroll-sprite-off.dll")
    default_manifest = next(data for path, data in pending if path.name == "payload-manifest-scroll-sprite-off.json")
    pending.extend(((base, default), (base_manifest, default_manifest)))
    pending.append((ROOT / "include" / "runtime_proxy_hashes.h", header(rows)))
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    if args.apply:
        for path, data in pending:
            path.write_bytes(data)
    print(f"{'Applied' if args.apply else 'Checked'} {len(NAMES)} Credits-off variants and the default alias")


if __name__ == "__main__":
    main()
