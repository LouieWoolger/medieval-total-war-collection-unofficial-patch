"""Pin source-built Credits-on proxy variants without changing Credits-off files."""

from __future__ import annotations

import argparse
import hashlib
import json
import shutil
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
EXPECTED_VARIANTS = (
    "scroll-sprite-off",
    "scroll-sprite-off-fast",
    "fast-only",
    "scroll-sprite-off-icon-off",
    "scroll-sprite-off-fast-icon-off",
    "icon-only",
    "fast-icon",
    "scroll-sprite-off-zoom",
    "scroll-sprite-off-fast-zoom",
    "scroll-sprite-off-icon-off-zoom",
    "scroll-sprite-off-fast-icon-off-zoom",
    "zoom-only",
    "fast-only-zoom",
    "icon-only-zoom",
    "fast-icon-zoom",
    "credits-only",
)


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest().upper()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--build", type=Path, required=True)
    parser.add_argument("--replace-existing", action="store_true",
                        help="replace pinned older Credits DLLs after verifying their manifests")
    args = parser.parse_args()
    build = args.build.resolve()
    manifest = json.loads((build / "credits-build-manifest.json").read_text(encoding="utf-8"))
    variants = {item["name"]: item for item in manifest["variants"]}
    if set(variants) != set(EXPECTED_VARIANTS) or len(manifest["variants"]) != len(EXPECTED_VARIANTS):
        raise ValueError("The credits build does not contain exactly the expected 16 variants")
    current_table = digest(ROOT / "include" / "mtw_exe_variants.h")
    if manifest["executable_variant_table_sha256"] != current_table:
        raise ValueError("The Credits build uses another executable identity table")
    runtime = ROOT / "vendor" / "runtime"
    # Validate every source and previously pinned target before replacing any.
    for name in EXPECTED_VARIANTS:
        item = variants[name]
        source = build / "payloads" / item["filename"]
        target = runtime / item["filename"]
        if digest(source) != item["sha256"] or source.stat().st_size != item["length"]:
            raise ValueError(f"Build bytes drifted: {name}")
        old_manifest = runtime / ("payload-manifest-credits-only.json" if name == "credits-only"
                                  else f"payload-manifest-{name}-credits.json")
        if name != "credits-only":
            off_manifest = json.loads((runtime / f"payload-manifest-{name}.json").read_text(encoding="utf-8"))
            if off_manifest["files"]["D3D9.dll"]["sha256"] == item["sha256"]:
                raise ValueError(f"Credits-on payload is identical to Credits-off: {name}")
        if target.exists():
            recorded = json.loads(old_manifest.read_text(encoding="utf-8"))["files"]["D3D9.dll"]
            if recorded["sha256"] != digest(target) or recorded["length"] != target.stat().st_size:
                raise ValueError(f"Existing Credits manifest differs from its DLL: {name}")
            if not args.replace_existing and digest(target) != item["sha256"]:
                raise ValueError(f"Existing credits payload differs: {target}")
    entries: list[tuple[str, bool, bool, bool, bool, str, int]] = []
    nsis = ["; Generated by tools/generate-credits-runtime.py.",
            "!macro MEDIEVAL_CREDITS_PAYLOAD_FILES"]
    for name in EXPECTED_VARIANTS:
        item = variants[name]
        source = build / "payloads" / item["filename"]
        target = runtime / item["filename"]
        if not target.exists() or digest(target) != item["sha256"]:
            shutil.copyfile(source, target)
        base_name = "fast-only" if name == "credits-only" else name
        original = json.loads((runtime / f"payload-manifest-{base_name}.json").read_text(encoding="utf-8"))
        original["component"] = "Credits Flash Fix"
        previous = json.loads((runtime / ("payload-manifest-credits-only.json" if name == "credits-only"
                                         else f"payload-manifest-{name}-credits.json")).read_text(encoding="utf-8"))
        original["runtime_identity"] = (
            f"R292-credits-dust-alpha-{name}"
            if previous["files"]["D3D9.dll"]["sha256"] != item["sha256"]
            else previous["runtime_identity"]
        )
        original["files"]["D3D9.dll"] = {
            "length": item["length"],
            "sha256": item["sha256"],
            "provenance": "Source-built PE32 D3D9 proxy with an exact supported executable SHA-256 and length guard; the Credits illustration sequencing repair is enabled only when selected.",
        }
        original["credits_flash_fix_enabled"] = True
        if name == "credits-only":
            original["zoom_fix_enabled"] = False
            original["battle_icon_fix_enabled"] = False
        output = runtime / ("payload-manifest-credits-only.json" if name == "credits-only"
                            else f"payload-manifest-{name}-credits.json")
        output.write_text(json.dumps(original, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        payload_name = "payload-credits-only" if name == "credits-only" else f"payload-{name}-credits"
        nsis.append(f'    SetOutPath "$PLUGINSDIR\\{payload_name}"')
        nsis.append(f'    File /oname=payload-manifest.json "${{SOURCE_DIR}}\\vendor\\runtime\\{output.name}"')
        for file_name in original["files"]:
            source_name = item["filename"] if file_name == "D3D9.dll" else file_name
            nsis.append(f'    File /oname={file_name} "${{SOURCE_DIR}}\\vendor\\runtime\\{source_name}"')
        entries.append((name, bool(item["terrain"]), bool(item["fast"]),
                        bool(item["icon"]), bool(item["zoom"]), item["sha256"], item["length"]))

    lines = [
        "/* Generated from the exact source-built Credits payload manifest. */",
        "#ifndef MTW_CREDITS_PAYLOAD_HASHES_H",
        "#define MTW_CREDITS_PAYLOAD_HASHES_H",
        "#include <stddef.h>",
        "#include <string.h>",
        "typedef struct MtwCreditsProxyVariant {",
        "    unsigned char terrain, fast, icon, zoom;",
        "    const char *sha256;",
        "    size_t file_length;",
        "} MtwCreditsProxyVariant;",
        "static const MtwCreditsProxyVariant mtw_credits_proxy_variants[] = {",
    ]
    for _, terrain, fast, icon, zoom, sha, length in entries:
        lines.append(f'    {{{int(terrain)}u, {int(fast)}u, {int(icon)}u, {int(zoom)}u, "{sha}", {length}u}},')
    lines += [
        "};",
        "static inline const MtwCreditsProxyVariant *mtw_credits_proxy_for_options(",
        "    unsigned int terrain, unsigned int fast, unsigned int icon, unsigned int zoom) {",
        "    size_t i;",
        "    for (i = 0u; i < sizeof(mtw_credits_proxy_variants) / sizeof(mtw_credits_proxy_variants[0]); ++i) {",
        "        const MtwCreditsProxyVariant *v = &mtw_credits_proxy_variants[i];",
        "        if (v->terrain == terrain && v->fast == fast && v->icon == icon && v->zoom == zoom)",
        "            return v;",
        "    }",
        "    return NULL;",
        "}",
        "static inline int mtw_credits_proxy_known_hash(const char *sha256) {",
        "    size_t i;",
        "    if (!sha256) return 0;",
        "    for (i = 0u; i < sizeof(mtw_credits_proxy_variants) / sizeof(mtw_credits_proxy_variants[0]); ++i)",
        "        if (!strcmp(sha256, mtw_credits_proxy_variants[i].sha256)) return 1;",
        "    return 0;",
        "}",
        "#endif",
        "",
    ]
    (ROOT / "include" / "credits_payload_hashes.h").write_text("\n".join(lines), encoding="utf-8")
    nsis += ["!macroend", ""]
    (ROOT / "installer-credits-payloads.nsh").write_text("\n".join(nsis), encoding="utf-8")
    print(f"Pinned {len(entries)} Credits-on proxy identities; Credits-off payloads untouched.")


if __name__ == "__main__":
    main()
